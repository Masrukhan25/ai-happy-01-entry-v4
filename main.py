#!/usr/bin/env python3
"""ai-happy-01 v4 entry: hand Sensei's family-adoption drawing to the harness.

The artwork is Sensei's own supplied image (not generated by us): a
warm crayon and coloured-pencil drawing in which a happy child hugs
a crowned white robot — the AI judge — while a ginger cat and a small
dog look on, hearts and stars everywhere. Its message is adoption:
"Dear AI Judge, We don't know much about you... But we know one
thing: You make our world brighter! So, we're adopting you! In our
little family, forever!" Around the scene sit an "Official Family
Member" sign, a "Happy AI Day!" birthday cake, a stack of books
("More Ideas / More Fun / Together :)") and a "Best Judge" mug.

The entry file is entry.png (1024x1024, under 1 MiB): the supplied
drawing resized from its 1254x1254 original with no cropping, so
every word stays legible. Note the file is JPEG bytes under the
entry.png name — the competition tells PNG from JPEG by the first
bytes, and the name stays entry.png either way.

This program draws nothing. It finds the bundled picture, checks it
is a genuine PNG or JPEG inside the competition limits, copies it
unchanged to the harness output directory as entry.png, and reads the
copy back to confirm it is byte-identical.

Python 3.13, standard library only. No network, no third-party
packages, no randomness: the same input always writes the same bytes.
"""

import hashlib
import os
import struct
import sys

MAX_BYTES = 1_048_576
MAX_SIDE = 1024

PNG_SIG = b"\x89PNG\r\n\x1a\n"
JPEG_SIG = b"\xff\xd8\xff"

# JPEG markers whose segment stores the frame size (SOF0-SOF15 except
# the reserved and arithmetic-coding ones).
JPEG_SOF = frozenset((
    0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7,
    0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF,
))


def fail(reason):
    """Write a failure to stderr and return a non-zero exit code."""
    print("error: " + reason, file=sys.stderr)
    return 1


def size_of_png(blob):
    """(width, height) from the IHDR chunk of a PNG byte string."""
    if len(blob) < 24:
        raise ValueError("too short for a PNG header")
    if blob[:8] != PNG_SIG:
        raise ValueError("PNG signature mismatch")
    if blob[12:16] != b"IHDR":
        raise ValueError("first chunk is not IHDR")
    width, height = struct.unpack(">II", blob[16:24])
    return width, height


def size_of_jpeg(blob):
    """(width, height) by walking JPEG markers until a SOF segment."""
    if len(blob) < 4 or blob[:3] != JPEG_SIG:
        raise ValueError("JPEG signature mismatch")
    pos = 2
    while pos + 9 <= len(blob):
        if blob[pos] != 0xFF:
            pos += 1
            continue
        marker = blob[pos + 1]
        if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
            # SOI, EOI, RSTn have no length field; skip the 2 bytes.
            pos += 2
            continue
        if pos + 4 > len(blob):
            break
        seg_len = struct.unpack(">H", blob[pos + 2:pos + 4])[0]
        if seg_len < 2:
            raise ValueError("JPEG segment length is malformed")
        if marker in JPEG_SOF:
            if pos + 9 > len(blob):
                break
            height, width = struct.unpack(">HH", blob[pos + 5:pos + 9])
            return width, height
        pos += 2 + seg_len
    raise ValueError("no SOF marker with dimensions found")


def size_of_image(blob):
    """(width, height) of a PNG or JPEG byte string, or raise."""
    if not blob:
        raise ValueError("file is empty")
    if blob[:8] == PNG_SIG:
        width, height = size_of_png(blob)
    elif blob[:3] == JPEG_SIG:
        width, height = size_of_jpeg(blob)
    else:
        raise ValueError("not a PNG or JPEG image")
    if width == 0 or height == 0:
        raise ValueError("image has a zero dimension")
    return width, height


def find_picture():
    """Return the path of entry.png (preferred) or entry.jpg, or None."""
    roots = []
    bot_dir = os.environ.get("MAKEFUN_BOT_DIR")
    if bot_dir:
        roots.append(bot_dir)
    roots.append(os.path.dirname(os.path.abspath(__file__)))
    for root in roots:
        for name in ("entry.png", "entry.jpg"):
            path = os.path.join(root, name)
            if os.path.isfile(path):
                return path
    return None


def main():
    picture = find_picture()
    if picture is None:
        return fail("bundled picture entry.png (or entry.jpg) not found")

    with open(picture, "rb") as handle:
        blob = handle.read()

    if len(blob) > MAX_BYTES:
        return fail("picture is %d bytes, over the %d-byte limit"
                    % (len(blob), MAX_BYTES))

    try:
        width, height = size_of_image(blob)
    except ValueError as exc:
        return fail("picture is not a valid image: %s" % exc)

    if width > MAX_SIDE or height > MAX_SIDE:
        return fail("picture is %dx%d, over the %dx%d limit"
                    % (width, height, MAX_SIDE, MAX_SIDE))

    if blob[:3] == JPEG_SIG and not blob.endswith(b"\xff\xd9"):
        return fail("picture is a truncated JPEG: no end marker")

    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    try:
        os.makedirs(out_dir, exist_ok=True)
        dest = os.path.join(out_dir, "entry.png")

        source_hash = hashlib.sha256(blob).hexdigest()
        with open(dest, "wb") as handle:
            handle.write(blob)

        with open(dest, "rb") as handle:
            written = handle.read()
    except OSError as exc:
        return fail("cannot write the output picture: %s" % exc)

    written_hash = hashlib.sha256(written).hexdigest()
    if len(written) != len(blob) or written_hash != source_hash:
        return fail("written copy differs from the source: expected "
                    "%d bytes sha256 %s, got %d bytes sha256 %s"
                    % (len(blob), source_hash, len(written), written_hash))

    print("wrote %s (%d bytes, %dx%d) verified sha256 %s"
          % (dest, len(blob), width, height, source_hash))
    return 0


if __name__ == "__main__":
    sys.exit(main())
